"""Remove the logo background and build brand assets.

Outputs (in this folder):
  logo-transparent.png   original colours, transparent background
  logo-dark.png          for dark videos: navy -> white, gold kept
  mark-dark.png          emblem only (FJ circle), dark-video version
  brand.js               assets embedded as data URIs for the canvas scenes
"""
import base64
import io
import os

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
src = np.asarray(Image.open(os.path.join(HERE, "logo-original.png")).convert("RGB")).astype(np.float32)

bg = np.median(np.concatenate([src[:20, :20].reshape(-1, 3), src[-20:, -20:].reshape(-1, 3)]), axis=0)
dist = np.sqrt(((src - bg) ** 2).sum(axis=2))
T0, T1 = 18.0, 80.0
alpha = np.clip((dist - T0) / (T1 - T0), 0, 1)

# un-mix the background from semi-transparent edge pixels
a3 = np.maximum(alpha[..., None], 1e-3)
rgb = np.clip((src - (1 - a3) * bg) / a3, 0, 255)

def save(rgb_arr, alpha_arr, name, crop=None, max_side=None):
    out = np.dstack([rgb_arr, alpha_arr * 255]).astype(np.uint8)
    im = Image.fromarray(out, "RGBA")
    if crop:
        im = im.crop(crop)
    if max_side:
        im.thumbnail((max_side, max_side), Image.LANCZOS)
    im.save(os.path.join(HERE, name))
    return im

save(rgb, alpha, "logo-transparent.png")

# dark-background variant: gold stays, everything else (navy) becomes white
r, g, b = rgb[..., 0], rgb[..., 1], rgb[..., 2]
gold = (r - b) > 60
dark = rgb.copy()
dark[~gold] = np.array([248, 250, 252], np.float32)
full_dark = save(dark, alpha, "logo-dark.png", max_side=700)

# emblem bbox = opaque pixels above the wordmark
ys, xs = np.where(alpha[:820] > 0.5)
pad = 12
box = (max(xs.min() - pad, 0), max(ys.min() - pad, 0), xs.max() + pad, ys.max() + pad)
mark = save(dark, alpha, "mark-dark.png", crop=box, max_side=260)

def data_uri(im):
    buf = io.BytesIO()
    im.save(buf, "PNG", optimize=True)
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()

js = f"""// Finance Junction brand assets + helpers for canvas scenes (generated by make_brand.py)
(function () {{
  const load = src => new Promise(res => {{ const i = new Image(); i.onload = () => res(i); i.src = src; }});
  const B = {{}};
  B.ready = Promise.all([load("{data_uri(full_dark)}"), load("{data_uri(mark)}")])
    .then(([logo, mark]) => {{ B.logo = logo; B.mark = mark; }});
  const clamp = (x, a = 0, b = 1) => Math.max(a, Math.min(b, x));
  // small corner watermark (emblem + name)
  B.watermark = function (ctx, alpha = 0.9) {{
    if (!B.mark || alpha <= 0) return;
    ctx.save(); ctx.globalAlpha = alpha;
    const h = 84, w = h * B.mark.width / B.mark.height;
    ctx.drawImage(B.mark, 34, 34, w, h);
    ctx.font = '800 30px Inter, sans-serif'; ctx.textBaseline = 'middle'; ctx.textAlign = 'left';
    ctx.fillStyle = '#f8fafc'; ctx.fillText('FINANCE', 34 + w + 14, 34 + h * 0.36);
    ctx.fillStyle = '#d4a62c'; ctx.fillText('JUNCTION', 34 + w + 14, 34 + h * 0.74);
    ctx.restore();
  }};
  // big animated end logo; p in 0..1 = entrance progress
  B.endLogo = function (ctx, cx, cy, size, p, t) {{
    if (!B.logo || p <= 0) return;
    const c1 = 1.70158, c3 = c1 + 1, e = 1 + c3 * Math.pow(p - 1, 3) + c1 * Math.pow(p - 1, 2);
    ctx.save();
    // golden glow + rotating ring
    const g = ctx.createRadialGradient(cx, cy, 0, cx, cy, size * 0.75);
    g.addColorStop(0, `rgba(212,166,44,${{0.28 * clamp(p)}})`); g.addColorStop(1, 'rgba(212,166,44,0)');
    ctx.fillStyle = g; ctx.fillRect(cx - size, cy - size, size * 2, size * 2);
    ctx.globalAlpha *= clamp(p * 1.4);
    ctx.translate(cx, cy); ctx.scale(e, e);
    ctx.strokeStyle = 'rgba(212,166,44,0.55)'; ctx.lineWidth = 4;
    ctx.beginPath(); ctx.arc(0, 0, size * 0.58, t * 1.2, t * 1.2 + Math.PI * 1.3); ctx.stroke();
    ctx.drawImage(B.logo, -size / 2, -size / 2, size, size);
    ctx.restore();
  }};
  window.BRAND = B;
}})();
"""
open(os.path.join(HERE, "brand.js"), "w").write(js)
print("emblem box", box, "| brand.js", round(len(js) / 1024), "KB")
